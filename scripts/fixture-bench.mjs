#!/usr/bin/env node
// Real-footage bench.
//
// Every other check in this repo is synthetic: canvases drawn in the test, boxes
// built by hand, strings grepped out of source. That leaves a whole class of bug
// invisible — an HEVC phone clip that decodes fine in theory, a 4K file that
// trips the proxy threshold in a unit test but not on a real `stsd` entry, a
// fragmented MP4 that reports 0×0 and gets imported as a still.
//
// This bench loads genuine, encoded files from `fixtures/video/` and runs the
// app's own import-time logic over their real bytes. It needs no browser: the
// container is parsed directly (scripts/lib/mp4.mjs) and the codec-sniffing
// entry point is imported from the built bundle.
//
//   node scripts/fixture-bench.mjs
//
// Fixtures are generated by scripts/make-fixtures.sh (ffmpeg draws a synthetic
// pattern, so nothing is downloaded and nothing is licensed).
import { readFileSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { probeMp4, codecName } from "./lib/mp4.mjs";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const DIR = join(ROOT, "fixtures/video");

if (!existsSync(DIR)) {
  console.error(`fixtures missing: ${DIR}\nrun: bash scripts/make-fixtures.sh`);
  process.exit(1);
}

// The pure-logic bundles are rebuilt by scripts/audit-build.mjs; import them from
// there so this bench exercises the same code the audit does.
const { detectVideoCodecHint } = await import("../.diag/b-utils.mjs");
const { shouldProxyVideo, proxySize, sourceFor } = await import("../.diag/b-proxy.mjs");

const files = readdirSync(DIR).filter((f) => /\.(mp4|webm|mov)$/i.test(f)).sort();
if (files.length === 0) {
  console.error("no fixtures found — run scripts/make-fixtures.sh");
  process.exit(1);
}

let passed = 0;
let failed = 0;
const check = (name, ok, detail = "") => {
  if (ok) {
    passed++;
    console.log("  PASS", name);
  } else {
    failed++;
    console.log("  FAIL", name, detail ? `— ${detail}` : "");
  }
};

const load = (f) => readFileSync(join(DIR, f));

console.log("real fixtures: parsing containers\n");
const probes = {};
for (const f of files) {
  probes[f] = probeMp4(load(f));
  const p = probes[f];
  console.log(
    `  ${f.padEnd(24)} ${p.ok ? `${p.width}×${p.height} ${codecName(p.video?.codec)} ${p.duration.toFixed(2)}s` : "unreadable: " + p.reason}`,
  );
}

// ---------------------------------------------------------------------------
// 1. The container reader tells the truth about real files.
// ---------------------------------------------------------------------------
console.log("\ncontainer reader");
{
  const p = probes["h264-720p-2s.mp4"];
  check("720p H.264 is read as 1280×720", p.width === 1280 && p.height === 720, `${p.width}×${p.height}`);
  check("its duration is a real 2 seconds", Math.abs(p.duration - 2) < 0.05, String(p.duration));
  check("its codec is avc1", p.video?.codec === "avc1", p.video?.codec);
  check("it has an audio track at 44100 Hz", p.audio?.codec === "mp4a" && Math.round(p.audio.sampleRate) === 44100, `${p.audio?.sampleRate}`);
}
{
  const p = probes["hevc-1080p-2s.mp4"];
  check("HEVC clip carries hvc1, not avc1", p.video?.codec === "hvc1", p.video?.codec);
  check("HEVC clip reads as 1920×1080", p.width === 1920 && p.height === 1080, `${p.width}×${p.height}`);
}
{
  const p = probes["h264-4k-1s.mp4"];
  check("4K clip reads as 3840×2160", p.width === 3840 && p.height === 2160, `${p.width}×${p.height}`);
}
{
  const p = probes["h264-vertical-2s.mp4"];
  check("a portrait phone clip keeps its orientation (h > w)", p.height > p.width, `${p.width}×${p.height}`);
}
{
  const p = probes["silent-1080p-2s.mp4"];
  check("a silent clip has a video track but NO audio track", !!p.video && !p.audio);
  check("…and it is still readable, not 'broken'", p.ok === true);
}
{
  const p = probes["fragmented-720p-2s.mp4"];
  // A fragmented file keeps its timing in `moof` boxes. Reporting 0 seconds is
  // the honest answer; the import path has to notice, not trust a zero.
  check("a fragmented MP4 reports 0 duration rather than guessing", p.duration === 0, String(p.duration));
  check("…so the import path must treat it as needing a real decode", p.duration <= 0);
}

// ---------------------------------------------------------------------------
// 2. The codec sniffer in the app agrees with the container, on real bytes.
// ---------------------------------------------------------------------------
console.log("\ncodec hint (app code, real bytes)");
for (const [file, want] of [
  ["h264-720p-2s.mp4", "H.264/AVC"],
  ["hevc-1080p-2s.mp4", "HEVC/H.265"],
  ["vp9-720p-2s.webm", "VP9"],
]) {
  const hint = await detectVideoCodecHint(new Blob([load(file)]));
  check(`${file} sniffs as ${want}`, hint === want, hint);
}

// ---------------------------------------------------------------------------
// 3. The proxy decision, made against the real dimensions.
// ---------------------------------------------------------------------------
console.log("\nproxy policy against real dimensions");
for (const [file, wanted] of [
  ["h264-720p-2s.mp4", false], // 720p already decodes quickly — a proxy is waste
  ["hevc-1080p-2s.mp4", true],
  ["h264-4k-1s.mp4", true],
  ["h264-vertical-2s.mp4", true],
  ["silent-1080p-2s.mp4", true],
]) {
  const p = probes[file];
  const d = shouldProxyVideo(
    { kind: "video", width: p.width, height: p.height, duration: p.duration, size: p.duration },
    {},
  );
  check(`${file} ${wanted ? "wants" : "does not want"} a proxy`, d.wanted === wanted, d.reason);
}

{
  // The portrait clip is the interesting one: proxySize caps HEIGHT, so a
  // 1080×1920 phone clip must become 406×720, not 720-something-wide.
  const p = probes["h264-vertical-2s.mp4"];
  const s = proxySize(p.width, p.height, 720);
  check("portrait proxy is sized by height: 406×720", s.width === 406 && s.height === 720, `${s.width}×${s.height}`);
  check("portrait proxy stays portrait", s.height > s.width);
  const wide = proxySize(3840, 2160, 720);
  check("4K proxy is 1280×720", wide.width === 1280 && wide.height === 720, `${wide.width}×${wide.height}`);
  check("proxy dimensions are always even", wide.width % 2 === 0 && wide.height % 2 === 0 && s.width % 2 === 0);
}

{
  // The rule the whole proxy design rests on: preview may take the proxy, export
  // never can. Check it with the real file names so a future refactor that swaps
  // the arguments is caught.
  const original = "h264-4k-1s.mp4";
  const proxy = "h264-4k-1s.proxy.webm";
  check("preview reads the proxy when one exists", sourceFor("preview", original, proxy) === proxy);
  check("preview falls back to the original with no proxy", sourceFor("preview", original) === original);
  check("export ALWAYS reads the original", sourceFor("export", original, proxy) === original);
}

console.log(`\nFIXTURE-BENCH: ${passed} passed, ${failed} failed`);
process.exit(failed ? 1 : 0);
