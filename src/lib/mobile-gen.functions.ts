import { createServerFn } from "@tanstack/react-start";
import { z } from "zod";
import { requireUser } from "@/integrations/mysupabase/middleware.server";
import { routeChat } from "./router/index.server";

const GenInput = z.object({
  projectId: z.string().uuid(),
  prompt: z.string().min(3).max(8000),
  appName: z.string().min(1).max(60),
});

const MOBILE_SYSTEM = `You are an expert React Native + Expo SDK 52 engineer.
Generate the source code for App.tsx of an Expo app based on the user's prompt.
Requirements:
- TypeScript, React Native + Expo components only.
- Import and use expo-notifications for local notifications,
  expo-task-manager + expo-background-fetch for background work,
  and expo-alarm-module for native alarms IF the prompt involves reminders/alarms.
- Request permissions at startup with Notifications.requestPermissionsAsync().
- Functional, complete, runnable as-is.
- Return ONLY the App.tsx code wrapped in a single \`\`\`tsx ... \`\`\` block. No prose.`;

function extractCode(s: string): string {
  const m = s.match(/```(?:tsx|ts|jsx|js)?\n([\s\S]*?)```/);
  return (m ? m[1] : s).trim();
}

function appJson(name: string) {
  const slug = name.toLowerCase().replace(/[^a-z0-9-]/g, "-");
  const pkg = `com.mayobuild.${name.toLowerCase().replace(/[^a-z0-9]/g, "")}`;
  return JSON.stringify(
    {
      expo: {
        name,
        slug,
        version: "1.0.0",
        orientation: "portrait",
        platforms: ["android"],
        android: {
          package: pkg,
          // Multi-window / split-screen multitasking
          androidStatusBar: { translucent: true },
          permissions: [
            "RECEIVE_BOOT_COMPLETED",
            "WAKE_LOCK",
            "SCHEDULE_EXACT_ALARM",
            "USE_EXACT_ALARM",
            "POST_NOTIFICATIONS",
            "FOREGROUND_SERVICE",
            "VIBRATE",
            "SET_ALARM",
            "QUERY_ALL_PACKAGES",
          ],
          // Declare ourselves as a candidate for: PDF viewer, default browser, link handler.
          // The user explicitly picks us via the system "Open with" / "Default apps" prompt.
          intentFilters: [
            {
              action: "VIEW",
              category: ["DEFAULT", "BROWSABLE"],
              data: [{ mimeType: "application/pdf" }, { scheme: "content" }, { scheme: "file" }],
            },
            {
              action: "VIEW",
              category: ["DEFAULT", "BROWSABLE"],
              data: [{ scheme: "http" }, { scheme: "https" }],
            },
          ],
        },
        androidNavigationBar: { visible: "leanback" },
        plugins: [
          "expo-notifications",
          "expo-task-manager",
          "expo-background-fetch",
        ],
        // resizeableActivity + supportsPictureInPicture for split-screen multitasking
        extra: { resizeableActivity: true, supportsPictureInPicture: true },
      },
    },
    null,
    2,
  );
}

function packageJson(name: string) {
  return JSON.stringify(
    {
      name: name.toLowerCase().replace(/[^a-z0-9-]/g, "-"),
      version: "1.0.0",
      main: "node_modules/expo/AppEntry.js",
      scripts: {
        start: "expo start",
        android: "expo run:android",
        build: "eas build -p android --profile production",
      },
      dependencies: {
        expo: "~52.0.0",
        "expo-status-bar": "~2.0.0",
        "expo-notifications": "~0.29.0",
        "expo-task-manager": "~12.0.0",
        "expo-background-fetch": "~13.0.0",
        "expo-alarm-module": "^1.1.0",
        react: "18.3.1",
        "react-native": "0.76.0",
      },
      devDependencies: { "@types/react": "~18.3.0", typescript: "^5.3.0" },
    },
    null,
    2,
  );
}

const README = (name: string) => `# ${name}

Generated by Mayobuild Studio.

## Run locally
\`\`\`bash
npm install
npx expo start
\`\`\`

## Build a Play-Store-ready .aab
\`\`\`bash
npm install -g eas-cli
eas login
eas build:configure
eas build -p android --profile production
\`\`\`

The app requests permissions for:
- Local + push notifications
- Background tasks
- Native exact alarms (\`SCHEDULE_EXACT_ALARM\`, \`SET_ALARM\`)
`;

const EAS_JSON = JSON.stringify(
  {
    cli: { version: ">= 5.0.0" },
    build: {
      production: { android: { buildType: "app-bundle" } },
      development: { developmentClient: true, distribution: "internal" },
    },
  },
  null,
  2,
);

export const generateMobileApp = createServerFn({ method: "POST" })
  .middleware([requireUser])
  .inputValidator((d: unknown) => GenInput.parse(d))
  .handler(async ({ data, context }) => {
    const { default: JSZip } = await import("jszip");
    const result = await routeChat("mobile_code", [
      { role: "system", content: MOBILE_SYSTEM },
      { role: "user", content: `App name: ${data.appName}\n\nPrompt:\n${data.prompt}` },
    ]);
    const appTsx = extractCode(result.text);

    const zip = new JSZip();
    zip.file("App.tsx", appTsx);
    zip.file("app.json", appJson(data.appName));
    zip.file("package.json", packageJson(data.appName));
    zip.file("README.md", README(data.appName));
    zip.file("eas.json", EAS_JSON);
    zip.file("tsconfig.json", JSON.stringify({ extends: "expo/tsconfig.base", compilerOptions: { strict: true } }, null, 2));
    zip.file(".gitignore", "node_modules\n.expo\ndist\n*.log\n");

    const buf = await zip.generateAsync({ type: "uint8array" });
    const b64 = Buffer.from(buf).toString("base64");

    await context.admin.from("generations").insert({
      project_id: data.projectId,
      user_id: context.user.id,
      task: "mobile_code",
      provider: result.provider,
      model: result.model,
      prompt: data.prompt,
      output: appTsx.slice(0, 50000),
      ok: true,
    });

    return {
      filename: `${data.appName.replace(/[^a-zA-Z0-9-]/g, "_")}-expo.zip`,
      base64: b64,
      provider: result.provider,
      model: result.model,
      previewCode: appTsx.slice(0, 4000),
    };
  });
